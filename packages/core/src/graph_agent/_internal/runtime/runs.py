"""Runs repository over `graph_agent.runs` (design section 5).

Raw SQL, one statement per operation. Every lease time comes from the database clock (`now()`).
After the claim, each mutation is fenced on `lease_owner` and `status = 'running'`, so an owner
that lost its lease (drain, takeover) can never write a terminal state: the call returns
`False` / `None` and the caller must stop. The fence is a token generated by `claim`
(`<owner>:<uuid>`), never the caller-chosen owner id, so the same worker re-claiming after an
expiry cannot be confused with its previous attempt. Recovery never writes `pending`.
"""

import uuid
from dataclasses import dataclass
from datetime import datetime, timedelta
from enum import StrEnum
from typing import Any, Final, LiteralString, Self

from psycopg import errors
from psycopg.rows import dict_row
from psycopg.types.json import Jsonb
from psycopg_pool import AsyncConnectionPool

DEFAULT_LIST_LIMIT: Final = 50


class RunStatus(StrEnum):
    PENDING = "pending"
    RUNNING = "running"
    SUCCESS = "success"
    ERROR = "error"
    INTERRUPTED = "interrupted"
    CANCELLED = "cancelled"


class ErrorCode(StrEnum):
    """Error codes shared by the runner, the sweep and the HTTP DTOs (T21 maps them to statuses)."""

    RUN_TIMEOUT = "run_timeout"
    FLOW_BUILD_FAILED = "flow_build_failed"
    FLOW_VERSION_MISMATCH = "flow_version_mismatch"
    THREAD_BUSY = "thread_busy"
    THREAD_INTERRUPTED = "thread_interrupted"
    TOO_MANY_RUNS = "too_many_runs"
    SHUTTING_DOWN = "shutting_down"  # admission closed by the shutdown
    ORPHAN_RETRIES_EXHAUSTED = "orphan_retries_exhausted"
    INTERNAL_ERROR = "internal_error"
    FLOW_NOT_FOUND = "flow_not_found"
    NOT_FOUND = "not_found"
    INVALID_REQUEST = "invalid_request"
    UNAUTHORIZED = "unauthorized"
    QUEUE_UNAVAILABLE = "queue_unavailable"
    RUN_HANDED_OVER = "run_handed_over"  # SSE only: an inline run drained for shutdown


class RunError(Exception):
    """`{code, message, retryable}`: the stored `runs.error` value and the HTTP error body."""

    def __init__(self, code: ErrorCode, message: str, retryable: bool = False) -> None:
        super().__init__(message)
        self.code = code
        self.message = message
        self.retryable = retryable

    def as_dict(self) -> dict[str, object]:
        return {"code": self.code.value, "message": self.message, "retryable": self.retryable}

    @classmethod
    def from_dict(cls, data: dict[str, Any]) -> Self:
        return cls(ErrorCode(data["code"]), data["message"], data["retryable"])


_TERMINAL: Final = frozenset(
    {RunStatus.SUCCESS, RunStatus.ERROR, RunStatus.INTERRUPTED, RunStatus.CANCELLED}
)
_TRANSITIONS: Final[dict[RunStatus, frozenset[RunStatus]]] = {
    RunStatus.PENDING: frozenset({RunStatus.RUNNING, RunStatus.CANCELLED}),
    RunStatus.RUNNING: _TERMINAL,
    **{status: frozenset[RunStatus]() for status in _TERMINAL},
}


def can_transition(source: RunStatus, target: RunStatus) -> bool:
    """The design section 5 "Transitions" table."""
    return target in _TRANSITIONS[source]


@dataclass(frozen=True, slots=True)
class Run:
    run_id: uuid.UUID
    thread_id: uuid.UUID
    flow: str
    flow_version: int
    tenant_id: str | None
    status: RunStatus
    input: object | None
    command: object | None
    error: RunError | None
    attempt: int
    lease_owner: str | None
    lease_expires_at: datetime | None
    cancel_requested: bool
    created_at: datetime
    started_at: datetime | None
    finished_at: datetime | None
    metadata: dict[str, Any]

    @classmethod
    def from_row(cls, row: dict[str, Any]) -> Self:
        error = row["error"]
        return cls(
            **{
                **row,
                "status": RunStatus(row["status"]),
                "error": None if error is None else RunError.from_dict(error),
            }
        )


@dataclass(frozen=True, slots=True)
class ThreadPin:
    """What the first run of a thread fixed for the rest of its life."""

    flow: str
    flow_version: int
    tenant_id: str | None


class ClaimOutcome(StrEnum):
    CLAIMED = "claimed"
    LOST = "lost"  # another executor owns the run, or it is already terminal
    THREAD_BUSY = "thread_busy"  # another run of the thread is running
    CANCELLED = "cancelled"  # cancel was requested: the run moved to `cancelled`, do not run it


@dataclass(frozen=True, slots=True)
class Claim:
    outcome: ClaimOutcome
    run: Run | None = None  # set when CLAIMED or CANCELLED
    token: str | None = None  # lease token; set only when CLAIMED


type RunRef = tuple[uuid.UUID, uuid.UUID]  # (run_id, thread_id): what a defer needs


@dataclass(frozen=True, slots=True)
class ExpiredRuns:
    exhausted: list[uuid.UUID]  # moved to error / orphan_retries_exhausted
    cancelled: list[uuid.UUID]  # cancel was requested: moved to cancelled, nothing to run
    redefer: list[RunRef]  # expired with attempts left: the caller defers `execute_run` again


_COLUMNS: LiteralString = """run_id, thread_id, flow, flow_version, tenant_id, status, input,
    command, error, attempt, lease_owner, lease_expires_at, cancel_requested, created_at,
    started_at, finished_at, metadata"""

_INSERT: LiteralString = f"""
INSERT INTO graph_agent.runs
    (run_id, thread_id, flow, flow_version, tenant_id, status, input, command, metadata)
VALUES (%s, %s, %s, %s, %s, 'pending', %s, %s, %s)
RETURNING {_COLUMNS}
"""

# `attempt` counts claims, so a run is claimed at most `max_attempts` times. A run with a pending
# cancel request is claimed straight into `cancelled` (its attempt is not consumed), even when
# exhausted: cancel beats exhaustion. An unexpired lease is never claimable, so a live run is
# never cancelled here.
_CLAIM: LiteralString = f"""
UPDATE graph_agent.runs
SET status = CASE WHEN cancel_requested THEN 'cancelled' ELSE 'running' END,
    lease_owner = CASE WHEN cancel_requested THEN NULL ELSE %(token)s END,
    lease_expires_at = CASE WHEN cancel_requested THEN NULL
        ELSE now() + make_interval(secs => %(lease_s)s::float8) END,
    attempt = CASE WHEN cancel_requested THEN attempt ELSE attempt + 1 END,
    started_at = CASE WHEN cancel_requested THEN started_at ELSE COALESCE(started_at, now()) END,
    finished_at = CASE WHEN cancel_requested THEN now() ELSE finished_at END
WHERE run_id = %(run_id)s AND (attempt < %(max_attempts)s OR cancel_requested)
  AND (status = 'pending' OR (status = 'running' AND lease_expires_at < now()))
RETURNING {_COLUMNS}
"""

_HEARTBEAT: LiteralString = """
UPDATE graph_agent.runs
SET lease_expires_at = now() + make_interval(secs => %(lease_s)s::float8)
WHERE run_id = %(run_id)s AND lease_owner = %(token)s AND status = 'running'
RETURNING cancel_requested
"""

_FINISH: LiteralString = """
UPDATE graph_agent.runs
SET status = %(status)s, error = %(error)s, finished_at = now(),
    lease_owner = NULL, lease_expires_at = NULL
WHERE run_id = %(run_id)s AND lease_owner = %(token)s AND status = 'running'
RETURNING run_id
"""

# A pending run is cancelled in the row; a running one only gets the flag (read by the heartbeat).
_REQUEST_CANCEL: LiteralString = """
UPDATE graph_agent.runs
SET cancel_requested = true,
    status = CASE WHEN status = 'pending' THEN 'cancelled' ELSE status END,
    finished_at = CASE WHEN status = 'pending' THEN now() ELSE finished_at END
WHERE run_id = %(run_id)s AND thread_id = %(thread_id)s AND status IN ('pending', 'running')
RETURNING status
"""

# A drain is not a failure: the lease expires now and the attempt is given back. The fence token
# is rotated so the draining owner can no longer heartbeat or finish.
_RELEASE_FOR_DRAIN: LiteralString = """
UPDATE graph_agent.runs
SET lease_owner = %(new_token)s, lease_expires_at = now(), attempt = GREATEST(attempt - 1, 0)
WHERE run_id = %(run_id)s AND lease_owner = %(token)s AND status = 'running'
RETURNING run_id
"""

_EXPIRED: LiteralString = """
WITH moved AS (
    UPDATE graph_agent.runs
    SET status = CASE WHEN cancel_requested THEN 'cancelled' ELSE 'error' END,
        error = CASE WHEN cancel_requested THEN NULL ELSE %(error)s END,
        finished_at = now(), lease_owner = NULL, lease_expires_at = NULL
    WHERE status = 'running' AND lease_expires_at < now()
      AND (attempt >= %(max_attempts)s OR cancel_requested)
    RETURNING run_id, thread_id, status
)
SELECT run_id, thread_id, status FROM moved
UNION ALL
SELECT run_id, thread_id, status FROM graph_agent.runs
WHERE status = 'running' AND lease_expires_at < now()
  AND attempt < %(max_attempts)s AND NOT cancel_requested
"""

_STALE_PENDING: LiteralString = """
SELECT run_id, thread_id FROM graph_agent.runs
WHERE status = 'pending' AND created_at < now() - make_interval(secs => %s::float8)
ORDER BY created_at, run_id
"""

# A thread is idle when none of its runs is pending or running and the last one ended (or, for
# a run that never finished, was created) before the cutoff. `idle` is the age of that last
# activity, measured by the database clock. Only threads in the prune window (idle for `idle_for`
# up to `idle_for + window`) or past `delete_after` come back: an older thread was already pruned
# a few times and is left alone until its whole-thread delete.
_IDLE_THREADS: LiteralString = """
SELECT thread_id, now() - max(COALESCE(finished_at, created_at)) AS idle
FROM graph_agent.runs
GROUP BY thread_id
HAVING bool_and(status NOT IN ('pending', 'running'))
   AND max(COALESCE(finished_at, created_at)) < now() - %(idle_for)s
   AND (max(COALESCE(finished_at, created_at)) >= now() - %(idle_for)s - %(window)s
        OR max(COALESCE(finished_at, created_at)) < now() - %(delete_after)s)
ORDER BY thread_id
"""

# The same rule for one thread, as a predicate: used right before a delete, because the list
# above can be minutes old by then.
_THREAD_ACTIVE: LiteralString = """EXISTS (
    SELECT 1 FROM graph_agent.runs AS r WHERE r.thread_id = %(thread_id)s
    AND (r.status IN ('pending', 'running')
         OR COALESCE(r.finished_at, r.created_at) >= now() - %(idle_for)s)
)"""

# Cron firings are deterministic (uuid5), so a repeated firing inserts nothing.
_INSERT_ONCE: LiteralString = """
INSERT INTO graph_agent.runs (run_id, thread_id, flow, flow_version, status, input, metadata)
VALUES (%s, %s, %s, %s, 'pending', %s, %s)
ON CONFLICT (run_id) DO NOTHING
RETURNING run_id
"""


class RunsRepository:
    def __init__(self, pool: AsyncConnectionPool) -> None:
        self._pool = pool

    async def _fetch(
        self, query: LiteralString, params: dict[str, Any] | tuple[Any, ...]
    ) -> list[dict[str, Any]]:
        # Each call is one implicit transaction on a pooled connection; no session state changes.
        async with self._pool.connection() as conn, conn.cursor(row_factory=dict_row) as cur:
            await cur.execute(query, params)
            return await cur.fetchall()

    async def create(
        self,
        *,
        thread_id: uuid.UUID,
        flow: str,
        flow_version: int,
        tenant_id: str | None = None,
        input: object | None = None,
        command: object | None = None,
        metadata: dict[str, Any] | None = None,
        run_id: uuid.UUID | None = None,
    ) -> Run:
        """Insert a `pending` run. The schema enforces exactly one of `input` / `command`."""
        rows = await self._fetch(
            _INSERT,
            (
                run_id or uuid.uuid4(),
                thread_id,
                flow,
                flow_version,
                tenant_id,
                None if input is None else Jsonb(input),
                None if command is None else Jsonb(command),
                Jsonb(metadata or {}),
            ),
        )
        return Run.from_row(rows[0])

    async def create_once(
        self,
        *,
        run_id: uuid.UUID,
        thread_id: uuid.UUID,
        flow: str,
        flow_version: int,
        input: object,
        metadata: dict[str, Any],
    ) -> bool:
        """Insert a `pending` run unless `run_id` exists. False: it already existed."""
        rows = await self._fetch(
            _INSERT_ONCE,
            (run_id, thread_id, flow, flow_version, Jsonb(input), Jsonb(metadata)),
        )
        return bool(rows)

    async def get(self, run_id: uuid.UUID, thread_id: uuid.UUID) -> Run | None:
        rows = await self._fetch(
            f"SELECT {_COLUMNS} FROM graph_agent.runs WHERE run_id = %s AND thread_id = %s",
            (run_id, thread_id),
        )
        return Run.from_row(rows[0]) if rows else None

    async def list_for_thread(
        self, thread_id: uuid.UUID, limit: int = DEFAULT_LIST_LIMIT
    ) -> list[Run]:
        """Newest first."""
        rows = await self._fetch(
            f"SELECT {_COLUMNS} FROM graph_agent.runs WHERE thread_id = %s "
            "ORDER BY created_at DESC, run_id DESC LIMIT %s",
            (thread_id, limit),
        )
        return [Run.from_row(r) for r in rows]

    async def has_running(self, thread_id: uuid.UUID) -> bool:
        """True while a run is `running` (an expired lease still counts until recovery moves it)."""
        rows = await self._fetch(
            "SELECT EXISTS (SELECT 1 FROM graph_agent.runs "
            "WHERE thread_id = %s AND status = 'running') AS running",
            (thread_id,),
        )
        return bool(rows[0]["running"])

    async def thread_pin(self, thread_id: uuid.UUID) -> ThreadPin | None:
        """Flow, version and tenant of the thread's first run; None for an unknown thread."""
        rows = await self._fetch(
            "SELECT flow, flow_version, tenant_id FROM graph_agent.runs WHERE thread_id = %s "
            "ORDER BY created_at, run_id LIMIT 1",
            (thread_id,),
        )
        return ThreadPin(**rows[0]) if rows else None

    async def claim(
        self, run_id: uuid.UUID, owner: str, lease_s: float, max_attempts: int
    ) -> Claim:
        """Atomically take a pending run, or a running one whose lease expired.

        Generates a fresh lease token (`<owner>:<uuid>`), stores it as `lease_owner` and returns
        it; heartbeat, finish and drain must present that token.
        """
        token = f"{owner}:{uuid.uuid4().hex}"
        try:
            rows = await self._fetch(
                _CLAIM,
                {
                    "run_id": run_id,
                    "token": token,
                    "lease_s": lease_s,
                    "max_attempts": max_attempts,
                },
            )
        except errors.UniqueViolation:
            # Only `runs_one_running_per_thread` can fire on this UPDATE.
            return Claim(ClaimOutcome.THREAD_BUSY)
        if not rows:
            return Claim(ClaimOutcome.LOST)
        run = Run.from_row(rows[0])
        if run.status is RunStatus.CANCELLED:
            return Claim(ClaimOutcome.CANCELLED, run)
        return Claim(ClaimOutcome.CLAIMED, run, token)

    async def heartbeat(self, run_id: uuid.UUID, token: str, lease_s: float) -> bool | None:
        """Extend the lease. Returns `cancel_requested`, or None if the lease is lost."""
        rows = await self._fetch(_HEARTBEAT, {"run_id": run_id, "token": token, "lease_s": lease_s})
        return rows[0]["cancel_requested"] if rows else None

    async def finish(
        self, run_id: uuid.UUID, token: str, status: RunStatus, error: RunError | None = None
    ) -> bool:
        """Write a terminal state. False means the lease was lost and nothing was written."""
        if status not in _TERMINAL:
            raise ValueError(f"not a terminal status: {status}")
        if (error is not None) != (status is RunStatus.ERROR):
            raise ValueError("error is required if and only if status is error")
        rows = await self._fetch(
            _FINISH,
            {
                "run_id": run_id,
                "token": token,
                "status": status.value,
                "error": None if error is None else Jsonb(error.as_dict()),
            },
        )
        return bool(rows)

    async def request_cancel(self, run_id: uuid.UUID, thread_id: uuid.UUID) -> RunStatus | None:
        """Cancel a pending run now, or flag a running one. None if unknown or already terminal."""
        rows = await self._fetch(_REQUEST_CANCEL, {"run_id": run_id, "thread_id": thread_id})
        return RunStatus(rows[0]["status"]) if rows else None

    async def release_for_drain(self, run_id: uuid.UUID, token: str) -> bool:
        """Graceful drain: expire the lease now and give the attempt back; status stays running.

        Rotates the fence token, so the caller can no longer heartbeat or finish. False if the
        lease was lost. The caller defers `execute_run`; the next claim takes over.
        """
        rows = await self._fetch(
            _RELEASE_FOR_DRAIN,
            {"run_id": run_id, "token": token, "new_token": f"drained:{uuid.uuid4().hex}"},
        )
        return bool(rows)

    async def expired(self, max_attempts: int) -> ExpiredRuns:
        """Orphan sweep. Exhausted runs move to `error`, cancel-requested ones to `cancelled`; the
        rest keep `running` for re-deferral."""
        error = RunError(
            ErrorCode.ORPHAN_RETRIES_EXHAUSTED,
            f"run lost its lease {max_attempts} times",
            retryable=False,
        )
        rows = await self._fetch(
            _EXPIRED, {"max_attempts": max_attempts, "error": Jsonb(error.as_dict())}
        )
        out = ExpiredRuns(exhausted=[], cancelled=[], redefer=[])
        for row in rows:
            match RunStatus(row["status"]):
                case RunStatus.ERROR:
                    out.exhausted.append(row["run_id"])
                case RunStatus.CANCELLED:
                    out.cancelled.append(row["run_id"])
                case _:
                    out.redefer.append((row["run_id"], row["thread_id"]))
        return out

    async def stale_pending(self, older_than_s: float) -> list[RunRef]:
        """Pending runs older than the threshold (crash between insert and defer), oldest first."""
        rows = await self._fetch(_STALE_PENDING, (older_than_s,))
        return [(r["run_id"], r["thread_id"]) for r in rows]

    async def idle_threads(
        self, idle_for: timedelta, *, window: timedelta, delete_after: timedelta
    ) -> list[tuple[uuid.UUID, timedelta]]:
        """Threads with no pending or running run whose last activity is older than `idle_for`
        (but at most `idle_for + window`, unless older than `delete_after`), with the age of
        that activity."""
        rows = await self._fetch(
            _IDLE_THREADS, {"idle_for": idle_for, "window": window, "delete_after": delete_after}
        )
        return [(r["thread_id"], r["idle"]) for r in rows]

    async def thread_is_idle(self, thread_id: uuid.UUID, idle_for: timedelta) -> bool:
        """Fresh per-thread check of the `idle_threads` rule."""
        rows = await self._fetch(
            f"SELECT NOT {_THREAD_ACTIVE} AS idle",
            {"thread_id": thread_id, "idle_for": idle_for},
        )
        return bool(rows[0]["idle"])

    async def delete_idle_thread(self, thread_id: uuid.UUID, idle_for: timedelta) -> int:
        """Delete the thread's runs only if it is still idle (rows deleted: 0 when it is not).

        Unlike `delete_thread` it never touches a thread that got a run since the idle list was
        built. Prune's delete; the API's explicit delete stays unconditional.
        """
        async with self._pool.connection() as conn, conn.cursor() as cur:
            await cur.execute(
                f"DELETE FROM graph_agent.runs WHERE thread_id = %(thread_id)s "
                f"AND NOT {_THREAD_ACTIVE}",
                {"thread_id": thread_id, "idle_for": idle_for},
            )
            return cur.rowcount

    async def delete_thread(self, thread_id: uuid.UUID) -> int:
        """Delete the thread's runs; refused (`thread_busy`) while one is running."""
        # The connection context rolls the DELETE back when we raise.
        async with self._pool.connection() as conn, conn.cursor() as cur:
            await cur.execute(
                "DELETE FROM graph_agent.runs WHERE thread_id = %s RETURNING status", (thread_id,)
            )
            rows = await cur.fetchall()
            if any(status == RunStatus.RUNNING for (status,) in rows):
                raise RunError(ErrorCode.THREAD_BUSY, "thread has a running run", retryable=True)
            return len(rows)
